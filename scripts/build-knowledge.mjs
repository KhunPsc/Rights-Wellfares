// Bundle vault/wiki/**/*.md into apps-script/Knowledge.js for the chatbot.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const wikiDir = join(root, 'vault', 'wiki');
const outFile = join(root, 'apps-script', 'Knowledge.js');

// Bookkeeping pages that don't help answer questions
const SKIP = new Set(['log.md']);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => {
      const p = join(dir, e.name);
      if (e.isDirectory()) return walk(p);
      return e.name.endsWith('.md') ? [p] : [];
    }),
  );
  return files.flat();
}

const files = (await walk(wikiDir)).sort();
const pages = [];
for (const file of files) {
  const path = relative(wikiDir, file).split(sep).join('/');
  if (SKIP.has(path)) continue;
  const text = (await readFile(file, 'utf8')).trim();
  if (text) pages.push({ path, text });
}

const banner = '// GENERATED by scripts/build-knowledge.mjs — do not edit. Run `npm run build`.\n';
await writeFile(outFile, `${banner}const KNOWLEDGE = ${JSON.stringify(pages, null, 1)};\n`, 'utf8');

const chars = pages.reduce((n, p) => n + p.text.length, 0);
console.log(`Knowledge.js: ${pages.length} pages, ${chars.toLocaleString()} chars`);
